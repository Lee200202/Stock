COVERED_YEARS = frozenset(int(d[:4]) for d in MARKET_HOLIDAYS)

_warned = set()


def is_market_holiday(d: date) -> bool:
    """這一天是不是休市日（不含週末，週末請另外用 weekday 判斷）。"""
    if d.year not in COVERED_YEARS:
        if d.year not in _warned:
            _warned.add(d.year)
            print(f"注意：休市日清單沒有 {d.year} 年的資料，這一年一律當成交易日。"
                  f"請執行 python scripts/update_holidays.py 更新。")
        return False
    return d.strftime("%Y-%m-%d") in MARKET_HOLIDAYS


def is_trading_day(d: date) -> bool:
    """平日且非休市日才算交易日。"""
    return d.weekday() < 5 and not is_market_holiday(d)


def why_closed(d: date) -> str:
    """給日誌用的一句話。回空字串代表這天有開盤。"""
    if d.weekday() >= 5:
        return "週末不開盤"
    if is_market_holiday(d):
        return "台股休市日"
    return ""
